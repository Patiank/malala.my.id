async function syncAndRestore() {
  console.log('🔄 Memulihkan seluruh 20 event dengan URL Cloudinary asli & status valid...');

  // 1. Sync directly to Google Cloud Firestore
  for (const ev of RESTORED_EVENTS) {
    await setDoc(doc(db, 'events', ev.id), ev, { merge: true });
    console.log(`   ✓ Firestore Updated: [${ev.id}] ${ev.title} (Image: ${ev.imageUrl.slice(0, 40)}...)`);
  }

  // 2. Sync to firestore_backup.json
  const backupPath = path.resolve('src/data/firestore_backup.json');
  if (fs.existsSync(backupPath)) {
    const backupData = JSON.parse(fs.readFileSync(backupPath, 'utf8'));
    backupData.eventItems = RESTORED_EVENTS;
    fs.writeFileSync(backupPath, JSON.stringify(backupData, null, 2), 'utf8');
    console.log('   ✓ firestore_backup.json disinkronkan!');
  }

  console.log('🎉 Pemulihan database Firestore & backup lokal selesai!');
  process.exit(0);
}

syncAndRestore().catch(e => {
  console.error('Error restoring events:', e);
  process.exit(1);
});
